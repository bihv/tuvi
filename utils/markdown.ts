import { marked } from 'marked'

/**
 * Normalizes and enhances raw AI markdown before parsing.
 * Auto-promotes unhashed section numbers to proper Markdown headers
 * so that sections like "5. Xu hướng..." or "5.1 Bối cảnh..." render as beautiful headers.
 */
export function preprocessAiMarkdown(raw: string): string {
  if (!raw) return ''

  const lines = raw.split('\n')
  const processedLines: string[] = []

  for (let i = 0; i < lines.length; i++) {
    let line = lines[i]
    const trimmed = line.trim()

    // 1. Top-level numbered sections (1 to 5) without markdown header hashes
    // Example: "1. Tổng quan Bản Mệnh" or "5. Xu hướng Vận hạn năm 2026..."
    if (/^[1-5]\.\s+(Tổng quan|Sự nghiệp|Tài lộc|Tình duyên|Xu hướng|Vận hạn)/i.test(trimmed)) {
      let icon = '🌟'
      if (/Tổng quan/i.test(trimmed)) icon = '🌟'
      else if (/Sự nghiệp|Quan Lộc/i.test(trimmed)) icon = '💼'
      else if (/Tài lộc|Tài Bạch/i.test(trimmed)) icon = '💰'
      else if (/Tình duyên|Phu Thê/i.test(trimmed)) icon = '❤️'
      else if (/Xu hướng|Vận hạn/i.test(trimmed)) icon = '⚡'

      line = `## ${icon} ${trimmed}`
    }
    // 2. Subsections like "5.1 Bối cảnh Lưu hạn tổng thể" or "5.2 Tứ Hóa..." without hashes
    else if (/^[1-5]\.[0-9]+\s+[^\n]+/i.test(trimmed) && !trimmed.startsWith('#')) {
      let icon = '🧭'
      if (/Tứ Hóa/i.test(trimmed)) icon = '🔄'
      else if (/Kế hoạch|hành động/i.test(trimmed)) icon = '🎯'
      else if (/Lịch trình|tháng|quý|kỳ hạn/i.test(trimmed)) icon = '📅'

      line = `### ${icon} ${trimmed}`
    }
    // 3. Existing ## sections without icons (e.g. "## 1. Tổng quan..." or "## 5. Xu hướng...")
    else if (/^##\s+([1-5])\.\s+([^\n]+)$/i.test(trimmed)) {
      const match = trimmed.match(/^##\s+([1-5])\.\s+([^\n]+)$/i)
      if (match) {
        const num = match[1]
        const title = match[2]
        const iconMap: Record<string, string> = {
          '1': '🌟',
          '2': '💼',
          '3': '💰',
          '4': '❤️',
          '5': '⚡',
        }
        line = `## ${iconMap[num] || '✨'} ${num}. ${title}`
      }
    }
    // 4. Existing ### subsections without icons
    else if (/^###\s+([1-5]\.[0-9]+)\s+([^\n]+)$/i.test(trimmed)) {
      const match = trimmed.match(/^###\s+([1-5]\.[0-9]+)\s+([^\n]+)$/i)
      if (match) {
        const num = match[1]
        const title = match[2]
        let icon = '🧭'
        if (/Tứ Hóa/i.test(title)) icon = '🔄'
        else if (/Kế hoạch|hành động/i.test(title)) icon = '🎯'
        else if (/Lịch trình|tháng|quý|kỳ hạn/i.test(title)) icon = '📅'

        line = `### ${icon} ${num} ${title}`
      }
    }

    processedLines.push(line)
  }

  return processedLines.join('\n')
}

/**
 * Enhances HTML generated by marked:
 * 1. Wraps tables in .ai-table-card and .ai-table-scroll
 * 2. Highlights Tứ Hóa keywords with signature colors (Lộc, Quyền, Khoa, Kỵ)
 * 3. Styles callout blockquotes (.ai-callout-tip, .ai-callout-warning)
 */
export function postprocessAiHtml(html: string): string {
  if (!html) return ''

  let result = html

  // 1. Wrap tables inside responsive glass cards
  result = result.replace(/<table>([\s\S]*?)<\/table>/g, (_match, tableInner) => {
    return `<div class="ai-table-card"><div class="ai-table-scroll"><table class="ai-table">${tableInner}</table></div></div>`
  })

  // 2. Classify blockquotes based on content (tip vs warning vs info)
  result = result.replace(/<blockquote>([\s\S]*?)<\/blockquote>/g, (_match, quoteInner) => {
    let calloutClass = 'ai-callout-info'
    if (/💡|khuyên|action|gợi ý|chiến lược/i.test(quoteInner)) {
      calloutClass = 'ai-callout-tip'
    } else if (/⚠️|lưu ý|cảnh báo|trở ngại|rủi ro/i.test(quoteInner)) {
      calloutClass = 'ai-callout-warning'
    }
    return `<blockquote class="ai-callout ${calloutClass}">${quoteInner}</blockquote>`
  })

  // 3. Highlight Tứ Hóa astrological keywords with elegant pill badges
  // Matches "Lưu Hóa Lộc", "Hóa Lộc", "Lưu Hóa Quyền", "Hóa Quyền", "Lưu Hóa Khoa", "Hóa Khoa", "Lưu Hóa Kỵ", "Hóa Kỵ"
  // Safe regex to only match outside of HTML tags/attributes
  const tuviBadgeRegex = /(Lưu Hóa Lộc|Hóa Lộc|Lưu Hóa Quyền|Hóa Quyền|Lưu Hóa Khoa|Hóa Khoa|Lưu Hóa Kỵ|Hóa Kỵ)(?![^<]*>)/g
  result = result.replace(tuviBadgeRegex, (match) => {
    let cls = 'loc'
    if (match.includes('Quyền')) cls = 'quyen'
    else if (match.includes('Khoa')) cls = 'khoa'
    else if (match.includes('Kỵ')) cls = 'ky'
    return `<span class="tuvi-badge tuvi-badge-${cls}">${match}</span>`
  })

  return result
}

/**
 * Main function: Takes markdown and returns beautifully styled and structured HTML.
 */
export function renderAiMarkdown(rawMarkdown: string): string {
  if (!rawMarkdown) return ''
  try {
    const preprocessed = preprocessAiMarkdown(rawMarkdown)
    const rawHtml = marked.parse(preprocessed) as string
    return postprocessAiHtml(rawHtml)
  } catch (err) {
    console.error('Failed to render AI markdown:', err)
    return `<p class="text-rose-500">Lỗi hiển thị nội dung: ${String(err)}</p>`
  }
}
